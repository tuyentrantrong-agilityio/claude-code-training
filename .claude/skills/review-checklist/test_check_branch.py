"""Tests for check_branch. Run: python .claude/skills/review-checklist/test_check_branch.py"""

import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import check_branch  # noqa: E402


class SubjectTest(unittest.TestCase):
    def test_good_subjects(self):
        for subject in ("feat: add rag compulsory security notebook", "fix: close hook bypasses",
                        "docs: add day 15 demo script", "chore: x1"):
            with self.subTest(subject=subject):
                self.assertIsNone(check_branch.check_subject(subject))

    def test_bad_format(self):
        for subject in ("Add feature", "feat: Add feature", "feat: add feature.", "feature: add x",
                        "feat:add x", "fix:", "feat: "):
            with self.subTest(subject=subject):
                self.assertIsNotNone(check_branch.check_subject(subject))

    def test_ai_mention_in_subject(self):
        self.assertIn("AI or Claude", check_branch.check_subject("docs: add evidence captured by claude"))

    def test_ai_mention_in_body(self):
        self.assertIsNotNone(check_branch.check_body("Co-Authored-By: Someone <a@b.c>"))
        self.assertIsNotNone(check_branch.check_body("Generated with a tool"))
        self.assertIsNone(check_branch.check_body("Explains why the cursor is validated."))

    def test_attribution_is_blocked(self):
        for text in ("feat: add x written by claude", "fix: ai-generated retry loop", "docs: notes made with ai",
                     "Co-authored-by: Claude <noreply@anthropic.com>", "Generated by a model",
                     "chore: claude generated config", "docs: drafted with the ai", "feat: add x by chatgpt"):
            with self.subTest(text=text):
                self.assertIsNotNone(check_branch.check_body(text))

    def test_naming_the_tool_as_the_subject_is_allowed(self):
        # The rule exists to stop AI credit lines, not to ban the tool's name (PR #17).
        for subject in ("docs: add the playbook for shipping a feature with claude code",
                        "feat: add claude code hooks for the kickoff", "docs: explain the ai review gate",
                        "chore: move the claude settings into one file"):
            with self.subTest(subject=subject):
                self.assertIsNone(check_branch.check_subject(subject))


class KnownCommitsTest(unittest.TestCase):
    LEGACY = "53956044966cb89baa297d7cd7e466ae713502a7"

    def entries(self, *commits):
        return ["\n" + "\x1f".join(c) for c in commits]

    def test_only_listed_commits_are_excused(self):
        entries = self.entries((self.LEGACY, "docs: add evidence captured by claude", ""),
                               ("b" * 40, "docs: add notes written by claude", ""),
                               ("c" * 40, "feat: add x", ""))
        self.assertEqual(check_branch.commit_problems(entries, {self.LEGACY}),
                         ["bbbbbbb docs: add notes written by claude: subject credits AI or Claude as an author"])

    def test_the_legacy_commit_is_listed_with_a_reason(self):
        known = check_branch.known_commits()
        self.assertEqual(known, {self.LEGACY})


class PathAndDiffTest(unittest.TestCase):
    def test_forbidden_paths(self):
        paths = ["day-02/auction/__pycache__/x.pyc", ".env", "app/.env.local", "a.pyc", ".env.example", "day-02/a.py"]
        self.assertEqual(check_branch.forbidden_paths(paths), paths[:4])

    def test_added_non_ascii_lines_only(self):
        diff = "\n".join([
            "+++ b/a.md",
            "+plain line",
            "+bad \u2014 line",
            "-removed \u2014 line",
            "+++ b/b.md",
            "+caf\u00e9",
        ])
        self.assertEqual(check_branch.added_non_ascii(diff), ["a.md: U+2014", "b.md: U+00E9"])


